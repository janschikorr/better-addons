#!/usr/bin/env python3
"""Inventory an AddOns folder: one record per .toc file, plus code size.

This is the first step of phase 2. It answers what is installed, which .toc
files exist per addon, what each one declares, and how much code there is to
read - before any of it is read.

Usage:
    python tools/inventory.py "E:/World of Warcraft/_forever_/Interface/AddOns"
    python tools/inventory.py <addons dir> --json out.json --markdown out.md

The addon folders are untrusted input: this script only reads, never executes.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

TOC_FIELD = re.compile(r"^\s*##\s*([^:]+):\s*(.*)$")
COLOUR_CODE = re.compile(r"\|c[0-9a-fA-F]{8}|\|r|\|T.*?\|t")

# Fields that matter for a manifest. Everything else is counted, not kept:
# some audio packages declare tens of thousands of per-quest fields.
KEEP = {
    "Interface", "Title", "Version", "Author", "Notes", "Category", "X-Category",
    "Dependencies", "RequiredDeps", "OptionalDeps", "OptionalDependencies",
    "LoadOnDemand", "LoadWith", "DefaultState", "SavedVariables",
    "SavedVariablesPerCharacter", "X-Part-Of", "X-Child-Of", "X-License",
    "X-Website", "X-Flavor", "AddonCompartmentFunc",
}
BETTER_ADDONS = re.compile(r"^X-BetterAddons-", re.IGNORECASE)

DEP_FIELDS = ("Dependencies", "RequiredDeps")
OPT_FIELDS = ("OptionalDeps", "OptionalDependencies")


def strip_colours(value: str) -> str:
    return COLOUR_CODE.sub("", value or "").strip()


def split_list(value: str) -> list[str]:
    return [part.strip() for part in re.split(r"[,\s]+", value or "") if part.strip()]


def read_toc(path: Path) -> dict:
    fields: dict[str, str] = {}
    extra = 0
    better: dict[str, str] = {}
    try:
        text = path.read_text(encoding="utf-8-sig", errors="replace")
    except OSError as error:
        return {"file": path.name, "error": str(error)}
    for line in text.splitlines():
        match = TOC_FIELD.match(line)
        if not match:
            continue
        key, value = match.group(1).strip(), match.group(2).strip()
        if BETTER_ADDONS.match(key):
            better[key] = value
        elif key in KEEP or key.startswith("Title-") or key.startswith("Notes-"):
            fields[key] = value
        else:
            extra += 1

    record = {
        "file": path.name,
        "title": strip_colours(fields.get("Title", "")),
        "version": fields.get("Version", ""),
        "interface": split_list(fields.get("Interface", "")),
        "author": strip_colours(fields.get("Author", "")),
        "depends": sorted({d for f in DEP_FIELDS for d in split_list(fields.get(f, ""))}),
        "optional": sorted({d for f in OPT_FIELDS for d in split_list(fields.get(f, ""))}),
        "saved_variables": split_list(fields.get("SavedVariables", "")),
        "load_on_demand": fields.get("LoadOnDemand", "") == "1",
        "part_of": fields.get("X-Part-Of", "") or fields.get("X-Child-Of", ""),
        "licence": fields.get("X-License", ""),
        "other_fields": extra,
        "better_addons": better,
    }
    return record


def inventory(root: Path) -> list[dict]:
    records = []
    for folder in sorted(p for p in root.iterdir() if p.is_dir()):
        lua = list(folder.rglob("*.lua"))
        files = [p for p in folder.rglob("*") if p.is_file()]
        records.append({
            "folder": folder.name,
            "lua_files": len(lua),
            "xml_files": len(list(folder.rglob("*.xml"))),
            "lua_kb": round(sum(p.stat().st_size for p in lua) / 1024),
            "total_mb": round(sum(p.stat().st_size for p in files) / 1048576, 1),
            "tocs": [read_toc(toc) for toc in sorted(folder.glob("*.toc"))],
        })
    return records


def as_markdown(records: list[dict], root: Path) -> str:
    lines = [
        "# AddOns inventory",
        "",
        f"Source: `{root}`  ",
        f"{len(records)} folders, "
        f"{sum(len(r['tocs']) for r in records)} .toc files, "
        f"{sum(r['lua_files'] for r in records)} Lua files, "
        f"{sum(r['lua_kb'] for r in records) / 1024:.1f} MB of Lua.",
        "",
        "Generated by `tools/inventory.py`. One manifest is needed per .toc file.",
        "",
        "| Addon | .toc | Version | Interface | Lua files | Lua kB | Total MB | Manifest |",
        "| --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for record in records:
        if not record["tocs"]:
            lines.append(
                f"| {record['folder']} | *(none)* | | | {record['lua_files']} | "
                f"{record['lua_kb']} | {record['total_mb']} | |"
            )
            continue
        for toc in record["tocs"]:
            manifest = "yes" if toc.get("better_addons") else "no"
            lines.append(
                f"| {record['folder']} | `{toc['file']}` | {toc.get('version', '')} | "
                f"{', '.join(toc.get('interface', []))} | {record['lua_files']} | "
                f"{record['lua_kb']} | {record['total_mb']} | {manifest} |"
            )

    lines += ["", "## Declared dependencies", ""]
    for record in records:
        for toc in record["tocs"]:
            if toc.get("depends") or toc.get("optional"):
                lines.append(f"**{record['folder']}/{toc['file']}**")
                if toc.get("depends"):
                    lines.append(f"- required: {', '.join(toc['depends'])}")
                if toc.get("optional"):
                    lines.append(f"- optional: {', '.join(toc['optional'])}")
                lines.append("")

    families = [r for r in records if any(t.get("part_of") for t in r["tocs"])]
    if families:
        lines += ["## Part of another addon", ""]
        for record in families:
            parents = sorted({t["part_of"] for t in record["tocs"] if t.get("part_of")})
            lines.append(f"- `{record['folder']}` → {', '.join(parents)}")
        lines.append("")

    multi = [r for r in records if len(r["tocs"]) > 1]
    if multi:
        lines += ["## Several .toc files", "",
                  "Each of these needs its own manifest; the slots can differ per game version.", ""]
        for record in multi:
            lines.append(f"- `{record['folder']}`: " + ", ".join(t["file"] for t in record["tocs"]))
        lines.append("")

    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("addons", type=Path, help="the Interface/AddOns folder")
    parser.add_argument("--json", type=Path, help="write the full inventory here")
    parser.add_argument("--markdown", type=Path, help="write a readable summary here")
    args = parser.parse_args()

    if not args.addons.is_dir():
        sys.exit(f"not a directory: {args.addons}")

    records = inventory(args.addons)
    if args.json:
        args.json.parent.mkdir(parents=True, exist_ok=True)
        args.json.write_text(json.dumps(records, indent=1, ensure_ascii=False), encoding="utf-8")
        print(f"json     {args.json}")
    text = as_markdown(records, args.addons)
    if args.markdown:
        args.markdown.parent.mkdir(parents=True, exist_ok=True)
        args.markdown.write_text(text, encoding="utf-8")
        print(f"markdown {args.markdown}")
    if not args.json and not args.markdown:
        sys.stdout.reconfigure(encoding="utf-8")
        print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
